/* font-gen: the screen's type (docs/recovery.md, "The screen"), rasterized at the build
 * with FreeType into a C header, so the screen itself links no font library and draws
 * the same pixels on every machine that builds it from the same font files.
 *
 *   font-gen OUT.h NAME FILE WEIGHT SIZE [NAME FILE WEIGHT SIZE]...
 *
 * NAME: the C name of the face (rs_font_NAME); FILE: a TrueType file; WEIGHT: the
 * value of a variable font's wght axis (0: the file's default instance); SIZE: pixels
 * per em. Each face holds Latin-1 and the few typographic marks the texts use; a code
 * point a face lacks is drawn as '?'. Glyphs are 16 levels of coverage, two pixels a
 * byte (the panel's GC16 has 16 levels). No kerning, no ligatures: the same advance
 * for a glyph wherever it stands.
 */
#include <ft2build.h>
#include FT_FREETYPE_H
#include FT_MULTIPLE_MASTERS_H
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static const unsigned extra[] = { 0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x2192, 0x2190 };

static void die(const char *m, const char *a)
{
	fprintf(stderr, "font-gen: %s %s\n", m, a ? a : "");
	exit(1);
}

int main(int argc, char **argv)
{
	if (argc < 6 || (argc - 2) % 4) die("usage: font-gen OUT.h NAME FILE WEIGHT SIZE...", NULL);
	FT_Library lib;
	if (FT_Init_FreeType(&lib)) die("no FreeType", NULL);
	FILE *o = fopen(argv[1], "w");
	if (!o) die("cannot write", argv[1]);
	fprintf(o, "/* generated by font-gen (ramenv/recovery/screen/font-gen.c); do not edit */\n");
	unsigned cps[256 + sizeof extra / sizeof *extra];
	int ncp = 0;
	for (unsigned c = 32; c < 127; c++) cps[ncp++] = c;
	for (unsigned c = 0xa0; c < 0x100; c++) cps[ncp++] = c;
	for (size_t i = 0; i < sizeof extra / sizeof *extra; i++) cps[ncp++] = extra[i];
	for (int a = 2; a < argc; a += 4) {
		const char *name = argv[a], *file = argv[a + 1];
		int weight = atoi(argv[a + 2]), size = atoi(argv[a + 3]);
		FT_Face f;
		if (FT_New_Face(lib, file, 0, &f)) die("cannot open", file);
		if (weight > 0) {
			FT_MM_Var *mm;
			if (FT_Get_MM_Var(f, &mm)) die("not a variable font:", file);
			FT_Fixed co[16];
			if (mm->num_axis > 16) die("too many axes:", file);
			int found = 0;
			for (FT_UInt i = 0; i < mm->num_axis; i++) {
				co[i] = mm->axis[i].def;
				if (mm->axis[i].tag == FT_MAKE_TAG('w', 'g', 'h', 't')) { co[i] = (FT_Fixed)weight << 16; found = 1; }
			}
			if (!found) die("no wght axis:", file);
			if (FT_Set_Var_Design_Coordinates(f, mm->num_axis, co)) die("cannot set the weight:", file);
			FT_Done_MM_Var(lib, mm);
		}
		if (FT_Set_Pixel_Sizes(f, 0, (FT_UInt)size)) die("cannot set the size:", file);
		int asc = (int)((f->size->metrics.ascender + 63) >> 6), desc = (int)((-f->size->metrics.descender + 63) >> 6);
		fprintf(o, "static const uint8_t rs_bits_%s[] = {\n", name);
		long off = 0;
		struct { unsigned cp; int x, y, w, h, adv; long off; } g[sizeof cps / sizeof *cps];
		int ng = 0;
		for (int i = 0; i < ncp; i++) {
			FT_UInt gi = FT_Get_Char_Index(f, cps[i]);
			if (!gi && cps[i] != ' ') continue;
			if (FT_Load_Glyph(f, gi, FT_LOAD_RENDER | FT_LOAD_TARGET_LIGHT)) continue;
			FT_Bitmap *b = &f->glyph->bitmap;
			if (b->pixel_mode != FT_PIXEL_MODE_GRAY && b->rows) die("not a grey bitmap in", file);
			g[ng].cp = cps[i];
			g[ng].x = f->glyph->bitmap_left;
			g[ng].y = f->glyph->bitmap_top;
			g[ng].w = (int)b->width;
			g[ng].h = (int)b->rows;
			g[ng].adv = (int)((f->glyph->advance.x + 32) >> 6);
			g[ng].off = off;
			int n = 0;
			for (unsigned r = 0; r < b->rows; r++)
				for (unsigned c = 0; c < b->width; c += 2) {
					const unsigned char *p = b->buffer + (long)r * b->pitch + c;
					unsigned hi = (p[0] * 15 + 127) / 255, lo = c + 1 < b->width ? (p[1] * 15 + 127) / 255 : 0;
					fprintf(o, "%u,%s", hi << 4 | lo, ++n % 24 ? "" : "\n");
					off++;
				}
			if (n % 24) fprintf(o, "\n");
			ng++;
		}
		fprintf(o, "0 };\nstatic const struct rs_glyph rs_glyphs_%s[] = {\n", name);
		for (int i = 0; i < ng; i++)
			fprintf(o, "{ %u, %d, %d, %d, %d, %d, %ld },\n", g[i].cp, g[i].x, g[i].y, g[i].w, g[i].h, g[i].adv, g[i].off);
		fprintf(o, "};\nstatic const struct rs_font rs_font_%s = { %d, %d, %d, %d, rs_glyphs_%s, rs_bits_%s };\n",
			name, size, asc, desc, ng, name, name);
		FT_Done_Face(f);
	}
	fclose(o);
	FT_Done_FreeType(lib);
	return 0;
}
